/** Default animation-key prefix of the phaser3 format: the sheet's base name, which is also its texture key. */
export const PHASER_ANIM_PREFIX = '{base}/';

/**
 * The profile with its animation names prefixed by `prefix` (tokens {base} {asset}); '' gives bare names. A
 * leading default prefix in the profile's pattern is replaced, not doubled. Godot's direction helper builds names
 * itself, so a literal prefix goes into its `animPrefix` setting too.
 */
export function withAnimPrefix(profile: ExportProfile, prefix: string): ExportProfile {
  const bare = profile.animationName.startsWith(PHASER_ANIM_PREFIX) ? profile.animationName.slice(PHASER_ANIM_PREFIX.length) : profile.animationName;
  const settings = 'animPrefix' in profile.settings && !/\{\w+\}/.test(prefix) ? { ...profile.settings, animPrefix: prefix } : profile.settings;
  return { ...profile, animationName: prefix + bare, settings };
}

/**
 * True when a format's own `{base}.json` is the generic sheet data (generic, GameMaker); every other format gets a
 * `{base}.sheet.json` copy of it so the export can be opened again in the app or read by any engine.
 */
export function ownsSheetData(profile: Pick<ExportProfile, 'files'>) {
  return profile.files.some((f) => f.name === '{base}.json' && f.template === GENERIC_JSON);
}

/**
 * The format packing trimmed frames into atlas pages (far less texture memory than a grid), whatever its own
 * default layout (`--atlas`). Special formats (RPG Maker, LPC) keep their fixed sheets.
 */
export function withAtlasLayout(profile: ExportProfile): ExportProfile {
  if (profile.special) return profile;
  return { ...profile, layout: { ...profile.layout, mode: 'atlas', trim: true, padding: Math.max(2, profile.layout.padding), extrude: Math.max(1, profile.layout.extrude) } };
}

