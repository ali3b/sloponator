/**
 * Export profiles. Every format (including the built-in engine formats) is a profile: layout settings plus
 * LiquidJS templates rendered over the ExportContext. Users duplicate a built-in and edit it to target a
 * custom engine; profiles are plain JSON so they can be shared and versioned.
 */
import type { ViewConfig } from '../view/camera.js';
import type { LayoutSettings } from '../layout/layout.js';

export interface ProfileFile {
  /**
   * Output file name pattern. If it contains {pageFile} or {page}, the template is rendered once per page
   * with `page`, `pageFrames` and `pageAnimations` available; otherwise once for the whole export.
   */
  name: string;
  template: string;
}

export interface ExportProfile {
  id: string;
  name: string;
  description: string;
  builtin: boolean;
  /** Special layouts with fixed engine conventions; null for the generic layout engine. */
  special: 'rpgmaker' | 'lpc' | null;
  layout: LayoutSettings;
  /** Image page file pattern: {base} {page} {clip} {dir} {n}. */
  pageFile: string;
  /** Frame name pattern: {clip} {dir} {i} {base}. */
  frameName: string;
  /** Animation name pattern: {clip} {dir} {base} {asset}. */
  animationName: string;
  files: ProfileFile[];
  /** Free-form settings exposed to templates as `settings.*` (editable in the UI). */
  settings: Record<string, string | number | boolean>;
  /** View settings the format requires (e.g. RPG Maker: 4 directions in its row order). */
  view?: Partial<ViewConfig>;
  /** Also write an animated GIF per animation for quick sharing. */
  gifPreviews: boolean;
}

